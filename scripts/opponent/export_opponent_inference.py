"""Export a checkpoint (or random architecture) for the standalone native benchmark.

Writes generated.hpp, weights.bin, reference.bin and manifest.json; no training/data needed.
"""
import argparse
import json
from pathlib import Path
import numpy as np
import torch
from opponent_model import Predictor, START


def export(args):
    torch.set_num_threads(1)
    torch.manual_seed(args.seed)
    config = dict(horizon=args.horizon, width=args.width, blocks=args.blocks,
                  context_size=args.context_size, heads=args.heads, hidden=args.hidden,
                  fusion=args.fusion, embedding=args.embedding)
    if args.checkpoint:
        saved = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
        if saved.get("architecture") != "conv-heads-gru-v1" or not saved["board"]:
            raise ValueError("requires a conv-heads-gru-v1 board checkpoint")
        config = {k: saved["args"][k] for k in config if k != "context_size"}
        config["context_size"] = saved["context_size"]
    model = Predictor(**config).eval()
    if args.checkpoint:
        model.load_state_dict(saved["state_dict"])
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    tensors, weights, offset = [], [], 0
    for name, parameter in model.named_parameters():
        values = parameter.detach().numpy().astype("<f4").ravel()
        tensors.append(dict(name=name, offset=offset, count=len(values), shape=list(parameter.shape)))
        weights.append(values)
        offset += len(values)
    np.concatenate(weights).tofile(out/"weights.bin")
    constants = "\n".join(f"inline constexpr int {k.upper()} = {v};" for k, v in config.items())
    entries = ",\n".join('    {"%s", %d, %d}' % (t["name"], t["offset"], t["count"]) for t in tensors)
    (out/"generated.hpp").write_text(
        "// Generated by scripts/opponent/export_opponent_inference.py\n#pragma once\n#include <cstddef>\n"
        "#include <string_view>\nnamespace generated {\n" + constants +
        '\nstruct Tensor { std::string_view name; std::size_t offset, count; };\n'
        'inline constexpr Tensor TENSORS[] = {\n' + entries + '\n};\n}\n')
    # Sparse, nontrivial boards and piece/context values. Include every intermediate boundary.
    board = (torch.rand(1, 1, 20, 10) < 0.3).float()
    context = torch.randn(1, config["context_size"])
    previous = torch.tensor([START])
    arrays = [board.flatten(), context.flatten()]
    with torch.no_grad():
        x = torch.cat((board, model.coordinates), 1)
        features = torch.cat([head(x) for head in model.heads], 1)
        conditioning = model.encode(board, context)
        hidden = model.initial(conditioning)[None]
        arrays += [features.flatten(), conditioning.flatten(), hidden.flatten()]
        for step in range(config["horizon"]):
            inputs = torch.cat((model.embedding(previous), conditioning), -1)[:, None]
            states, hidden = model.gru(inputs, hidden)
            arrays += [model.output(states[:, 0]).flatten(), hidden.flatten()]
            previous = torch.tensor([step % 8])
    np.concatenate([a.numpy().ravel() for a in arrays]).astype("<f4").tofile(out/"reference.bin")
    manifest = dict(architecture="conv-heads-gru-v1", config=config, seed=args.seed,
                    checkpoint=str(args.checkpoint) if args.checkpoint else None,
                    parameters=offset, weight_bytes=offset*4, tensors=tensors,
                    reference="board, context, head features, fusion, initial hidden, (logits, hidden) per step")
    (out/"manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"Exported {offset:,} FP32 parameters to {out}")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", required=True)
    p.add_argument("--checkpoint")
    for name, default in dict(horizon=8, width=4, blocks=2, context_size=52, heads=32,
                              hidden=128, fusion=256, embedding=16, seed=1).items():
        p.add_argument("--" + name.replace("_", "-"), type=int, default=default)
    args = p.parse_args()
    for name in ("horizon", "width", "context_size", "heads", "hidden", "fusion", "embedding"):
        if getattr(args, name) < 1:
            p.error(name + " must be positive")
    if args.blocks < 0:
        p.error("blocks must be nonnegative")
    export(args)
